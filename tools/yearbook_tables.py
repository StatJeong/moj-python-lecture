def table(text, cols, types=None):
    rows = [line.split() for line in text.strip().splitlines()]
    df = pd.DataFrame(rows, columns=cols)
    for c in cols:
        df[c] = df[c].astype((types or {}).get(c, int))
    return df


def main():
    OUT.mkdir(parents=True, exist_ok=True)

    cap = table(CAPACITY, ["연도", "수용정원", "1일평균수용인원", "수용률"], {"수용률": float})
    calc = (cap["1일평균수용인원"] / cap["수용정원"] * 100).round(1)
    diff = (calc - cap["수용률"]).abs()
    assert len(cap) == 35 and cap["연도"].tolist() == list(range(1991, 2026))
    assert diff.max() <= 0.1 + 1e-9, cap[diff > 0.1]

    staff = table(STAFF, ["연도", "정원", "현원", "남성현원", "여성현원"])
    assert (staff["남성현원"] + staff["여성현원"] == staff["현원"]).all()

    off = table(OFFENSE, OFFENSE_COLS)
    assert (off[OFFENSE_COLS[2:]].sum(axis=1) == off["계"]).all()

    age = table(AGE, AGE_COLS)
    assert (age[AGE_COLS[2:]].sum(axis=1) == age["계"]).all()
    assert (age["계"] == off["계"]).all()

    for name, df in [("capacity_1991_2025", cap), ("staff_2016_2025", staff),
                     ("offense_2016_2025", off), ("age_2016_2025", age)]:
        df.to_csv(OUT / f"{name}.csv", index=False, encoding="utf-8")
        print(f"{name}.csv: {df.shape}")
    print("수용률 재계산과 연보 값의 최대 차이:", round(diff.max(), 2))


if __name__ == "__main__":
    main()
